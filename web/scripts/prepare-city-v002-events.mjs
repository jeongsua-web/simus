// Artifact preparation and optional READ ONLY inventory. There is deliberately
// no apply mode. Run from web; no QA, HTTP calls, migrations or writes to a DB.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { eventManifest, preparedLocation } from '../src/lib/city-v002-event-mapping.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
if (args.some(arg => !['--audit'].includes(arg))) throw Error('Only --audit is supported; this tool never applies SQL.');
const content = JSON.parse(await readFile(path.join(root, 'web/src/lib/data/initial-session-content.json'), 'utf8'));
const seed = await readFile(path.join(root, 'db/seed_exhibition.sql'), 'utf8');
const q = value => `'${String(value).replaceAll("'", "''")}'`;
const json = value => value === null ? 'NULL::jsonb' : `${q(JSON.stringify(value))}::jsonb`;
const choiceId = (number, order) => `40000000-0000-0000-0000-${String(number * 10 + order).padStart(12, '0')}`;
const eventRows = [], choiceRows = [];
for (const original of content.situations) {
  const row = eventManifest.events.find(row => row.number === original.number);
  // These are the ACTUAL stable IDs recorded in the original seed, not newly
  // invented UUIDs. At apply time existing rows are resolved by their own code/ID.
  if (!seed.includes(`${q(row.seed_situation_id)},${q(row.code)},${q(original.title)}`))
    throw Error(`Original seed identity not found: ${row.code}`);
  eventRows.push(`(${q(row.seed_situation_id)}::uuid,${q(row.code)},${q(original.title)},${original.number},${json(preparedLocation(row.code))})`);
  for (const choice of original.choices) {
    const id = choiceId(original.number, choice.number), s = choice.scores;
    if (!seed.includes(`${q(id)},${q(choice.label)},${choice.number},`)) throw Error(`Original choice not found: ${id}`);
    const importance = Math.max(Math.abs(s.order), Math.abs(s.morality)) > 1 ? 'MAJOR' : 'NORMAL';
    choiceRows.push(`(${q(row.code)},${q(id)}::uuid,${q(choice.label)},${choice.number},${q(importance)},${s.order},${s.morality},${s.happiness},${s.safety},${s.cleanliness},${s.pollution})`);
  }
}
const sql = `-- GENERATED by web/scripts/prepare-city-v002-events.mjs. NOT APPLIED.
-- Requires approved schema through 018. DEVELOPMENT DATABASE ONLY.
-- After user approval, review and supply psql variables session_id and development_database.
-- Existing IDs/text/choices/scores/locations are never overwritten. No running session is touched.
\\set ON_ERROR_STOP on
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='120s';
CREATE TEMP TABLE phase2_target ON COMMIT DROP AS
  SELECT :'session_id'::uuid AS id, :'development_database'::text AS database_name;
SELECT id FROM simus.simulation_sessions WHERE id=(SELECT id FROM phase2_target) FOR UPDATE;
DO $guard$ BEGIN
  IF current_database() IS DISTINCT FROM (SELECT database_name FROM phase2_target) THEN
    RAISE EXCEPTION 'Explicit development database name does not match'; END IF;
  IF NOT EXISTS (SELECT 1 FROM simus.simulation_sessions s JOIN phase2_target t USING(id)
    WHERE s.status='DRAFT' AND s.npc_motion->>'map_version'=${q(eventManifest.map_version)}
      AND s.npc_motion->>'path_version'=${q(eventManifest.path_version)}) THEN
    RAISE EXCEPTION 'An existing v002 DRAFT with the supported path is required'; END IF;
  IF EXISTS (SELECT 1 FROM simus.participant_sessions WHERE session_id=(SELECT id FROM phase2_target)) THEN
    RAISE EXCEPTION 'Target must have no participants'; END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='simus'
    AND table_name='npc_event_states' AND column_name='location_occupancy') THEN
    RAISE EXCEPTION 'Approved schema migration 018 is required first'; END IF;
END $guard$;
CREATE TEMP TABLE phase2_events(seed_id uuid,code text PRIMARY KEY,title text,display_order integer,event_location jsonb) ON COMMIT DROP;
INSERT INTO phase2_events VALUES
${eventRows.join(',\n')};
CREATE TEMP TABLE phase2_choices(code text,seed_id uuid,label text,display_order integer,importance text,
  dx smallint,dy smallint,h numeric,s numeric,c numeric,p numeric) ON COMMIT DROP;
INSERT INTO phase2_choices VALUES
${choiceRows.join(',\n')};
-- Reject any pre-existing authored-content divergence rather than "fixing" it.
DO $guard$ BEGIN
  IF EXISTS (SELECT 1 FROM simus.session_situations t JOIN phase2_events e USING(code)
    WHERE t.session_id=(SELECT id FROM phase2_target) AND
      (t.title IS DISTINCT FROM e.title OR t.body IS DISTINCT FROM e.title OR t.is_generic)) THEN
    RAISE EXCEPTION 'Existing original content differs; review manually'; END IF;
  IF EXISTS (SELECT 1 FROM simus.session_situations t JOIN phase2_events e USING(code)
    WHERE t.session_id=(SELECT id FROM phase2_target) AND (
      (SELECT count(*) FROM simus.session_choices c WHERE c.session_id=t.session_id AND c.situation_id=t.id)
        <> (SELECT count(*) FROM phase2_choices c WHERE c.code=e.code)
      OR EXISTS (SELECT 1 FROM phase2_choices expected WHERE expected.code=e.code AND NOT EXISTS (
        SELECT 1 FROM simus.session_choices actual WHERE actual.session_id=t.session_id AND actual.situation_id=t.id
          AND actual.display_order=expected.display_order AND actual.label=expected.label
          AND actual.importance=expected.importance AND actual.alignment_dx=expected.dx AND actual.alignment_dy=expected.dy
          AND actual.happiness_base=expected.h AND actual.safety_base=expected.s AND actual.cleanliness_base=expected.c
          AND (SELECT coalesce(sum(r.pollution_base),0) FROM simus.choice_region_effects r
            WHERE r.session_id=actual.session_id AND r.situation_id=actual.situation_id AND r.choice_id=actual.id)=expected.p
      )))) THEN RAISE EXCEPTION 'Existing choices/scores differ or are incomplete; review manually'; END IF;
  IF EXISTS (SELECT 1 FROM phase2_events e JOIN simus.session_situations t ON t.id=e.seed_id
    AND t.session_id=(SELECT id FROM phase2_target) WHERE t.code<>e.code) THEN
    RAISE EXCEPTION 'Stable seed UUID belongs to another code; never relink it'; END IF;
END $guard$;
CREATE TEMP TABLE phase2_missing ON COMMIT DROP AS
  SELECT e.* FROM phase2_events e WHERE NOT EXISTS (SELECT 1 FROM simus.session_situations t
    WHERE t.session_id=(SELECT id FROM phase2_target) AND t.code=e.code);
-- Missing original rows may only be seeded into the original provisional city region.
-- Do not fabricate region IDs or rewrite existing per-region effects.
DO $guard$ BEGIN
  IF EXISTS (SELECT 1 FROM phase2_missing) AND NOT EXISTS (SELECT 1 FROM simus.session_regions
    WHERE session_id=(SELECT id FROM phase2_target) AND code='EXHIBITION_CITY') THEN
    RAISE EXCEPTION 'Missing original EXHIBITION_CITY region; no speculative region is created'; END IF;
END $guard$;
INSERT INTO simus.session_situations(session_id,id,code,title,body,display_order,event_location,is_generic)
  SELECT t.id,e.seed_id,e.code,e.title,e.title,e.display_order,NULL,false FROM phase2_missing e CROSS JOIN phase2_target t;
INSERT INTO simus.session_choices(session_id,situation_id,id,label,display_order,importance,
  alignment_dx,alignment_dy,happiness_base,safety_base,cleanliness_base)
  SELECT t.id,e.seed_id,c.seed_id,c.label,c.display_order,c.importance,c.dx,c.dy,c.h,c.s,c.c
  FROM phase2_missing e JOIN phase2_choices c USING(code) CROSS JOIN phase2_target t;
INSERT INTO simus.choice_region_effects(session_id,situation_id,choice_id,region_id,pollution_base)
  SELECT t.id,e.seed_id,c.seed_id,r.id,c.p FROM phase2_missing e JOIN phase2_choices c USING(code)
  CROSS JOIN phase2_target t JOIN simus.session_regions r ON r.session_id=t.id AND r.code='EXHIBITION_CITY';
-- Preserve ALL non-null coordinates, including the unavailable Phase 1 baseline.
-- BLOCKED rows remain NULL; candidate_location is NEVER used for activation.
UPDATE simus.session_situations t SET event_location=e.event_location
  FROM phase2_events e,phase2_target target WHERE t.session_id=target.id AND t.code=e.code
    AND t.event_location IS NULL AND NOT t.is_generic AND e.event_location IS NOT NULL;
SELECT t.code,t.id,t.event_location FROM simus.session_situations t
  JOIN phase2_events e USING(code) WHERE t.session_id=(SELECT id FROM phase2_target) ORDER BY t.code;
COMMIT;
`;
await mkdir(path.join(root, 'db/content'), { recursive: true });
await mkdir(path.join(root, 'docs/placement/phase2'), { recursive: true });
await writeFile(path.join(root, 'db/content/city-v002-events-phase2-draft.sql'), sql);

if (args.includes('--audit')) {
  const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 5000 });
  let db;
  try {
    db = await pool.connect();
    await db.query('BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY');
    await db.query("SET LOCAL statement_timeout='15s'");
    const columns = (await db.query(`SELECT table_name,column_name,data_type FROM information_schema.columns
      WHERE table_schema='simus' AND table_name IN ('session_situations','session_choices','npc_event_states')
      ORDER BY table_name,ordinal_position`)).rows;
    const sessions = (await db.query(`SELECT id,status,npc_motion->>'map_version' AS map_version,
      npc_motion->>'path_version' AS path_version FROM simus.simulation_sessions ORDER BY id`)).rows;
    const situations = (await db.query(`SELECT session_id,id,code,title,body,event_location,is_generic,
      (SELECT jsonb_agg(to_jsonb(c)-'session_id'-'situation_id' ORDER BY c.display_order,c.id)
        FROM simus.session_choices c WHERE c.session_id=t.session_id AND c.situation_id=t.id) AS choices
      FROM simus.session_situations t ORDER BY session_id,display_order,id`)).rows;
    const effects = (await db.query(`SELECT session_id,situation_id,choice_id,region_id,pollution_base
      FROM simus.choice_region_effects ORDER BY session_id,situation_id,choice_id,region_id`)).rows;
    const summary = sessions.map(session => {
      const rows = situations.filter(t => t.session_id === session.id);
      const comparison = content.situations.map(original => {
        const mapping = eventManifest.events.find(e => e.number === original.number);
        const actual = rows.find(t => t.code === mapping.code);
        if (!actual) return { code: mapping.code, actual_id: null, content_matches: false, reason: 'MISSING_CODE' };
        const choices = actual.choices ?? [];
        const matches = actual.title === original.title && actual.body === original.title &&
          choices.length === original.choices.length && original.choices.every(expected => {
            const c = choices.find(c => c.display_order === expected.number), s = expected.scores;
            const pollution = effects.filter(e => e.session_id === session.id && e.situation_id === actual.id && e.choice_id === c?.id)
              .reduce((sum, e) => sum + Number(e.pollution_base), 0);
            return c && c.label === expected.label && c.alignment_dx === s.order && c.alignment_dy === s.morality &&
              Number(c.happiness_base) === s.happiness && Number(c.safety_base) === s.safety &&
              Number(c.cleanliness_base) === s.cleanliness && pollution === s.pollution;
          });
        return { code: mapping.code, actual_id: actual.id, seed_id_matches: actual.id === mapping.seed_situation_id,
          content_matches: matches, existing_location_preserved: actual.event_location };
      });
      return { ...session, original_count: rows.filter(t => eventManifest.events.some(e => e.code === t.code)).length,
        missing_codes: eventManifest.events.filter(e => !rows.some(t => t.code === e.code)).map(e => e.code),
        located_count: rows.filter(t => t.event_location).length, comparison };
    });
    await db.query('ROLLBACK');
    const report = { captured_at: new Date().toISOString(), transaction: 'REPEATABLE READ READ ONLY; ROLLBACK',
      qa_executed: false, data_changed: false, summary, columns, situations, effects };
    await writeFile(path.join(root, 'docs/placement/phase2/db-read-only-inventory.json'), JSON.stringify(report, null, 2)+'\n');
    console.log(JSON.stringify(summary.map(({ comparison, ...session }) => ({ ...session,
      original_content_matches: comparison.filter(e => e.content_matches).length }))));
  } finally { if (db) db.release(); await pool.end(); }
}
console.log(`Prepared DRAFT-only seed/mapping SQL (sha256 ${createHash('sha256').update(sql).digest('hex')}); NOT APPLIED. No QA executed.`);
